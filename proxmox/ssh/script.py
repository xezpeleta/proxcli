"""Generator for the idempotent `auth setup` bash script.

This module is **pure** — it has no Proxmox or SSH dependencies — so the script
text can be unit-tested and previewed with `--dry-run` without any cluster.

The generated script runs on a PVE node as ``root@pam`` and:

1. Creates (or syncs) the proxcli custom roles with their privilege sets.
2. Creates an API token for the given user — or regenerates its secret —
   capturing the one-time secret via ``pvesh ... --output-format json``.
3. Binds each role to the token on the right ACL path.

It communicates structured results back to the caller by printing lines of the
form ``PROXCLI:<EVENT>:<args>`` on stdout.  The caller (see :mod:`proxmox.ssh.runner`)
parses these into a :class:`~proxmox.ssh.runner.SetupResult`.
"""

from __future__ import annotations

from dataclasses import dataclass, field


def _sh(value: str) -> str:
    """Single-quote ``value`` for safe interpolation into a bash script.

    Handles embedded single quotes via the standard ``'"'"'`` idiom.
    """
    return "'" + value.replace("'", "'\"'\"'") + "'"


@dataclass(frozen=True)
class SetupSpec:
    """Inputs for the generated setup script.

    Attributes:
        pve_user: Proxmox user the token is created for, e.g. ``root@pam``.
        token_name: Token ID, e.g. ``proxcli``.
        privsep: If True (default) the token gets *separated* privileges
            (effective perms = token ACLs only). If False the token inherits
            the full privileges of the user.
        regenerate: If True and the token already exists, rotate its secret.
            If False and the token exists, report ``TOKEN_EXISTS`` (the secret
            cannot be recovered — Proxmox stores it once).
        roles: Mapping of role name -> privilege string (comma-separated).
        acls: Ordered list of ``(path, role)`` pairs to bind the token to.
    """

    pve_user: str
    token_name: str
    privsep: bool = True
    regenerate: bool = False
    roles: dict[str, str] = field(default_factory=dict)
    acls: list[tuple[str, str]] = field(default_factory=list)


def generate_setup_script(spec: SetupSpec) -> str:
    """Return the bash setup script for the given :class:`SetupSpec`.

    The script is idempotent and safe to re-run. It requires ``root@pam`` on a
    PVE node (``pveum``/``pvesh`` only work as root).
    """
    if not spec.pve_user or not spec.token_name:
        raise ValueError("pve_user and token_name are required")
    if not spec.roles:
        raise ValueError("at least one role is required")

    lines: list[str] = []
    a = lines.append

    a("#!/usr/bin/env bash")
    a("# Generated by `proxmox auth setup --via ssh`.")
    a("# Creates the proxcli roles, an API token, and ACLs on this PVE host.")
    a("# Idempotent: safe to re-run. Requires root@pam (pveum/pvesh need root).")
    a("set -uo pipefail")
    a("")
    a(f"PVE_USER={_sh(spec.pve_user)}")
    a(f"TOKEN={_sh(spec.token_name)}")
    a(f"PRIVSEP={_sh('1' if spec.privsep else '0')}")
    a(f"REGENERATE={_sh('1' if spec.regenerate else '0')}")
    a('UG="${PVE_USER}!${TOKEN}"')
    a("")
    a('# Emit a parseable result line consumed by proxcli.')
    a('ok() { printf "PROXCLI:%s\\n" "$1"; }')
    a("")
    a('# Extract the token "value" field from pvesh JSON output.')
    a('# Handles both {"value":"..."} and the wrapped {"data":{"value":"..."}}.')
    a('_extract_secret() {')
    a('  local out="$1" sec')
    a('  sec=$(printf \'%s\' "$out" | python3 -c "')
    a("    import sys, json")
    a("    d = json.load(sys.stdin)")
    a("    v = d.get('value') if isinstance(d, dict) else None")
    a("    if v is None and isinstance(d, dict):")
    a("        v = (d.get('data') or {}).get('value')")
    a("    print(v or '')")
    a('  " 2>/dev/null) || true')
    a('  if [ -z "$sec" ]; then')
    a('    # grep fallback if python3 is unavailable')
    a('    sec=$(printf \'%s\' "$out" \\')
    a('      | grep -oE \'"value"[[:space:]]*:[[:space:]]*"[^"]+"\' \\')
    a('      | head -1 \\')
    a('      | sed -E \'s/.*"value"[[:space:]]*:[[:space:]]*"([^"]+)".*/\\1/\')')
    a('  fi')
    a('  printf \'%s\' "$sec"')
    a("}")
    a("")
    a("# ---- Roles (idempotent: create or sync privileges) ----")
    a("role_ensure() {")
    a('  local name="$1" privs="$2"')
    a('  if pveum role list 2>/dev/null | grep -qw "$name"; then')
    a('    if pveum role modify "$name" --privs "$privs" >/dev/null 2>&1; then')
    a('      ok "ROLE_UPDATED:${name}"')
    a("    else")
    a('      ok "ROLE_UPDATE_FAILED:${name}"')
    a("    fi")
    a("  else")
    a('    if pveum role add "$name" --privs "$privs" >/dev/null 2>&1; then')
    a('      ok "ROLE_CREATED:${name}"')
    a("    else")
    a('      ok "ROLE_CREATE_FAILED:${name}"')
    a("    fi")
    a("  fi")
    a("}")
    a("")
    for role_name, privs in spec.roles.items():
        a(f'role_ensure {_sh(role_name)} {_sh(privs)}')
    a("")
    a("# ---- API token ----")
    a('TOKEN_PATH="/access/users/${PVE_USER}/token/${TOKEN}"')
    a('if pvesh get "$TOKEN_PATH" >/dev/null 2>&1; then')
    a('  if [ "$REGENERATE" = "1" ]; then')
    a('    OUT=$(pvesh set "$TOKEN_PATH" --regenerate 1 --output-format json 2>/dev/null) || true')
    a('    SECRET=$(_extract_secret "$OUT")')
    a('    if [ -n "$SECRET" ]; then')
    a('      ok "TOKEN_REGENERATED:${UG}"; ok "TOKEN_SECRET:${SECRET}"')
    a("    else")
    a('      ok "TOKEN_REGEN_FAILED:${UG}"')
    a("    fi")
    a("  else")
    a('    ok "TOKEN_EXISTS:${UG}"')
    a("  fi")
    a("else")
    a('  OUT=$(pvesh create "$TOKEN_PATH" --privsep "$PRIVSEP" --output-format json 2>/dev/null) || true')
    a('  SECRET=$(_extract_secret "$OUT")')
    a('  if [ -n "$SECRET" ]; then')
    a('    ok "TOKEN_CREATED:${UG}"; ok "TOKEN_SECRET:${SECRET}"')
    a("  else")
    a('    ok "TOKEN_CREATE_FAILED:${UG}"')
    a("  fi")
    a("fi")
    a("")
    a("# ---- ACLs (idempotent: aclmod sets the triple) ----")
    a("acl_ensure() {")
    a('  local path="$1" role="$2"')
    a('  if pveum acl modify "$path" --tokens "$UG" --roles "$role" >/dev/null 2>&1; then')
    a('    ok "ACL_SET:${path}:${role}"')
    a("  else")
    a('    ok "ACL_FAILED:${path}:${role}"')
    a("  fi")
    a("}")
    a("")
    for path, role in spec.acls:
        a(f'acl_ensure {_sh(path)} {_sh(role)}')
    a("")
    a('ok "DONE"')
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Manual (copy-paste) command list — the flat pveum/pvesh commands the
# setup script wraps, emitted for the user to review and run by hand on a
# node. No SSH transport required.
# ---------------------------------------------------------------------------


def generate_manual_commands(spec: SetupSpec) -> str:
    """Return flat, copy-pasteable ``pveum``/``pvesh`` commands for manual setup.

    Unlike :func:`generate_setup_script` (a wrapped bash script piped over SSH
    that reports structured ``PROXCLI:`` results), this produces plain commands
    the user can review and paste directly into a root shell on a PVE node.
    Each role line is idempotent (``add ... || modify ...``) so the whole block
    is safe to re-run. No SSH access is required — this is the default mode.
    """
    if not spec.pve_user or not spec.token_name:
        raise ValueError("pve_user and token_name are required")
    if not spec.roles:
        raise ValueError("at least one role is required")

    ug = f"{spec.pve_user}!{spec.token_name}"
    token_path = f"/access/users/{spec.pve_user}/token/{spec.token_name}"
    privsep = "1" if spec.privsep else "0"

    lines: list[str] = []
    a = lines.append

    a("# ===================================================================")
    a("# proxcli permission setup — run on a Proxmox node as root (root@pam).")
    a("# Idempotent: safe to re-run. Review, then paste the whole block.")
    a("# ===================================================================")
    a("")
    a("# 1. Create (or sync) the proxcli roles.")
    a("#    `pveum role add` creates a new role; `pveum role modify` updates an")
    a("#    existing one. The `||` fallback makes each line work either way.")
    a("")
    for name, privs in spec.roles.items():
        a(f"pveum role add {_sh(name)} --privs {_sh(privs)} 2>/dev/null \\")
        a(f"  || pveum role modify {_sh(name)} --privs {_sh(privs)}")
        a("")
    a("# 2. Create the API token. The JSON output contains a \"value\" field —")
    a("#    that is your one-time token secret (shown only here; copy it).")
    if spec.regenerate:
        a("#    Rotating an existing token's secret:")
        a(f"pvesh set {_sh(token_path)} --regenerate 1 --output-format json")
    else:
        a(f"pvesh create {_sh(token_path)} --privsep {privsep} --output-format json")
        a("#    If the token already exists and you want a new secret, use instead:")
        a(f"#    pvesh set {_sh(token_path)} --regenerate 1 --output-format json")
    a("")
    a("# 3. Bind each role to the token on the right ACL path.")
    a("")
    for path, role in spec.acls:
        a(f"pveum acl modify {_sh(path)} --tokens {_sh(ug)} --roles {_sh(role)}")
    a("")
    a("# Done! Verify on the node with:  pveum acl list")
    a("# Then save the token secret on your workstation (proxmox will prompt")
    a("# for it, or run `proxmox auth setup --no-write` for a JSON template).")
    return "\n".join(lines) + "\n"
